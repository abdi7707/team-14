import { build } from "esbuild";

// Bundles the API, including the TypeScript workspace packages, into one ESM file.
// pdfkit stays external because it reads its own data files from node_modules at runtime.
await build({
  entryPoints: ["src/index.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  outfile: "dist/index.mjs",
  sourcemap: true,
  external: ["pdfkit", "pg-native"],
  // Bundled CommonJS dependencies still call require() and read __dirname.
  banner: {
    js: [
      'import { createRequire as __createRequire } from "node:module";',
      'import { fileURLToPath as __fileURLToPath } from "node:url";',
      'import { dirname as __pathDirname } from "node:path";',
      "const require = __createRequire(import.meta.url);",
      "const __filename = __fileURLToPath(import.meta.url);",
      "const __dirname = __pathDirname(__filename);",
    ].join("\n"),
  },
  logLevel: "info",
});
